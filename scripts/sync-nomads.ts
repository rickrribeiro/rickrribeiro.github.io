/**
 * `npm run sync:nomads` — pulls the public trip log from nomads.com and writes
 * src/content/trips.json (generated; don't edit by hand — curated places live in journey.json).
 *
 * The public profile page embeds every trip as JSON (`{"trip_id":…,"epoch_start":…}`),
 * so no login or API key is needed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { root } from './load-content-fs';

const handle = process.argv[2] ?? 'rickrribeiro';
const url = `https://nomads.com/@${handle}`;
const out = path.join(root, 'src/content/trips.json');

interface RawTrip {
  epoch_start: number;
  epoch_end: number;
  city_slug: string;
  city: string;
  latitude: string;
  longitude: string;
  trip_length: number;
}

// country slug → ISO code, built from Intl so every country is covered.
const slug = (s: string) =>
  s
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const names = new Intl.DisplayNames(['en'], { type: 'region' });
const countryBySlug = new Map<string, string>();
for (let a = 65; a <= 90; a++)
  for (let b = 65; b <= 90; b++) {
    const code = String.fromCharCode(a, b);
    const name = names.of(code);
    // first code wins, so current codes (FR) beat deprecated aliases (FX) with the same name
    if (name && name !== code && !countryBySlug.has(slug(name))) countryBySlug.set(slug(name), code);
  }
Object.entries({ 'hong-kong': 'HK', macau: 'MO', 'united-states': 'US', 'united-kingdom': 'GB', 'south-korea': 'KR', 'north-korea': 'KP', taiwan: 'TW', 'czech-republic': 'CZ', 'ivory-coast': 'CI', russia: 'RU', vietnam: 'VN', turkey: 'TR' }).forEach(([k, v]) => countryBySlug.set(k, v));
const countrySlugs = [...countryBySlug.keys()].sort((a, b) => b.length - a.length);

function countryOf(citySlug: string): string {
  const hit = countrySlugs.find((c) => citySlug === c || citySlug.endsWith(`-${c}`));
  if (!hit) throw new Error(`Can't infer country from "${citySlug}" — add it to the overrides in scripts/sync-nomads.ts`);
  return countryBySlug.get(hit)!;
}

const day = (epoch: number) => new Date(epoch * 1000).toISOString().slice(0, 10);

const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 (portfolio sync script)' } });
if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
const html = await res.text();
const matches = html.match(/\{[^{}]*"epoch_start"[^{}]*\}/g) ?? [];
if (!matches.length) throw new Error('No trips found in the page — the nomads.com markup may have changed.');

const seen = new Set<string>();
const trips = matches
  .map((m) => JSON.parse(m) as RawTrip)
  .filter((t) => (seen.has(`${t.epoch_start}-${t.city_slug}`) ? false : (seen.add(`${t.epoch_start}-${t.city_slug}`), true)))
  .sort((a, b) => a.epoch_start - b.epoch_start)
  .map((t) => ({
    city: t.city.replace(/, [A-Z]{2}$/, ''),
    country: countryOf(t.city_slug),
    lat: Number(Number(t.latitude).toFixed(3)),
    lon: Number(Number(t.longitude).toFixed(3)),
    start: day(t.epoch_start),
    end: day(t.epoch_end),
    days: Math.max(0, t.trip_length),
  }));

const since = html.match(/Digital Nomad since (\d{2})\/(\d{4})/);
const data = {
  $comment: 'GENERATED by `npm run sync:nomads` from the public nomads.com profile. Do not edit — curated places (home, studied, spoke) live in journey.json.',
  source: url,
  syncedAt: new Date().toISOString().slice(0, 10),
  nomadSince: since ? `${since[2]}-${since[1]}` : null,
  trips,
};

const before = fs.existsSync(out) ? (JSON.parse(fs.readFileSync(out, 'utf8')).trips?.length ?? 0) : 0;
fs.writeFileSync(out, JSON.stringify(data, null, 2) + '\n');
const countries = new Set(trips.map((t) => t.country));
const cities = new Set(trips.map((t) => `${t.city}|${t.country}`));
console.log(`✔ ${trips.length} trips (${trips.length - before >= 0 ? '+' : ''}${trips.length - before}), ${cities.size} cities, ${countries.size} countries → src/content/trips.json`);
